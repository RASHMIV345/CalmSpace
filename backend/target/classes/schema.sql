CREATE TABLE IF NOT EXISTS app_user(
  id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL,
  email VARCHAR(120) UNIQUE NOT NULL, password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(12) NOT NULL, therapist_id BIGINT, share_consent BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS mood_entry(
  id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id BIGINT NOT NULL,
  mood INT NOT NULL CHECK (mood BETWEEN 1 AND 5), note VARCHAR(500),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS journal_entry(
  id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id BIGINT NOT NULL, prompt VARCHAR(200),
  content VARCHAR(5000) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS assignment(
  id BIGINT AUTO_INCREMENT PRIMARY KEY, therapist_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
  title VARCHAR(120) NOT NULL, detail VARCHAR(1000), done BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS safety_plan(
  user_id BIGINT PRIMARY KEY, warning_signs VARCHAR(2000), coping VARCHAR(2000),
  people VARCHAR(2000), reasons VARCHAR(2000));
